"""Turn the drone-portrait image into the logo, the icons and the drones for the opening film.

    python3 scripts/digitize.py path/to/portrait.webp

The image (supplied by the owner) is already a picture made of points of light,
so nothing is generated here — it is used as it is, and the film's drones are
traced from its own lights:
  frontend/portrait.webp   the image, for the end of the film (the drones dissolve into it)
  frontend/logo.webp       a square crop round the face — the logo everywhere in the app
  frontend/icon-180.png    iOS home screen; icon-192.png and icon-512.png for the manifest
  frontend/portrait.js     every light in the image as a drone: [x, y, colour, brightness]
                           on a 1000-wide grid, colours from a 32-colour palette
Needs Pillow and numpy only.
"""
from __future__ import annotations

import json
import os
import sys
from typing import List, Tuple

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FRONT = os.path.join(ROOT, "frontend")
# the face, as a share of the frame: the square the logo and the icons are cut from
FACE = (0.505, 0.43, 0.70)          # centre x, centre y, side (of the height)
MAX_DRONES = 2600
GRID = 1000


def face_square(im: Image.Image) -> Image.Image:
    W, H = im.size
    side = int(H * FACE[2])
    x0 = int(W * FACE[0] - side / 2)
    y0 = int(H * FACE[1] - side / 2)
    return im.crop((x0, y0, x0 + side, y0 + side))


def lights(im: Image.Image) -> List[Tuple[float, float, np.ndarray, float]]:
    """Every point of light: a local brightness peak, strongest first, no two closer than a few pixels."""
    a = np.asarray(im.filter(ImageFilter.GaussianBlur(3))).astype(float)    # a dot's tint, not its white-hot core
    lum = np.asarray(im.convert("L").filter(ImageFilter.GaussianBlur(1.6))).astype(float)
    H, W = lum.shape
    k = 3
    pad = np.pad(lum, k, mode="edge")
    peak = np.ones_like(lum, dtype=bool)
    for dy in range(-k, k + 1):
        for dx in range(-k, k + 1):
            if dx or dy:
                peak &= lum >= pad[k + dy:k + dy + H, k + dx:k + dx + W]
    ys, xs = np.nonzero(peak & (lum > 40))
    order = np.argsort(-lum[ys, xs])
    rmin = 6.5 * W / 1446                                  # about the spacing of the lights in the picture
    grid = {}
    out = []
    for o in order:
        y, x = int(ys[o]), int(xs[o])
        gx, gy = int(x // rmin), int(y // rmin)
        if any((px - x) ** 2 + (py - y) ** 2 < rmin * rmin
               for ddx in (-1, 0, 1) for ddy in (-1, 0, 1) for (px, py) in grid.get((gx + ddx, gy + ddy), ())):
            continue
        grid.setdefault((gx, gy), []).append((x, y))
        col = a[y, x]
        out.append((x, y, col, float(lum[y, x])))
        if len(out) >= MAX_DRONES:
            break
    return out


def palette(cols: np.ndarray, n: int = 32) -> Tuple[np.ndarray, np.ndarray]:
    """k-means in plain numpy: n colours for the drone sprites, and each light's nearest one"""
    rng = np.random.default_rng(3)
    c = cols[rng.choice(len(cols), n, replace=False)].copy()
    for _ in range(25):
        lab = ((cols[:, None, :] - c[None]) ** 2).sum(2).argmin(1)
        for i in range(n):
            if (lab == i).any():
                c[i] = cols[lab == i].mean(0)
    return c, lab


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    im = Image.open(sys.argv[1]).convert("RGB")
    W, H = im.size

    film = im.resize((1200, round(1200 * H / W)), Image.LANCZOS)
    film.save(os.path.join(FRONT, "portrait.webp"), "WEBP", quality=80, method=6)
    sq = face_square(im)
    sq.resize((256, 256), Image.LANCZOS).save(os.path.join(FRONT, "logo.webp"), "WEBP", quality=82, method=6)
    for n in (180, 192, 512):
        sq.resize((n, n), Image.LANCZOS).quantize(256, dither=Image.Dither.NONE).save(os.path.join(FRONT, "icon-%d.png" % n), optimize=True)

    pts = lights(im)
    cols = np.array([p[2] for p in pts])
    # light, not paint: lift each colour towards full brightness so the sprites glow like the picture
    cols = np.clip(cols * (235.0 / np.maximum(cols.max(1, keepdims=True), 1)), 0, 255)
    pal, lab = palette(cols)
    S = GRID / W
    flat: List[int] = []
    for (x, y, _, l), ci in zip(pts, lab):
        flat += [round(x * S), round(y * S), int(ci), min(9, round(l / 255 * 9))]
    hexes = ["#%02X%02X%02X" % tuple(int(v) for v in c) for c in pal]
    with open(os.path.join(FRONT, "portrait.js"), "w", encoding="utf-8") as f:
        f.write("/* Footy — the opening film's drones, traced from the lights in the logo portrait\n"
                "   (frontend/portrait.webp). Generated by scripts/digitize.py; don't edit by hand.\n"
                "   %d drones as [x, y, colour, brightness 0-9] on a %dx%d grid; colours index `pal`. */\n"
                "'use strict';\nconst PORTRAIT = {w:%d, h:%d, pal:%s, d:%s};\n"
                % (len(pts), GRID, round(H * S), GRID, round(H * S), json.dumps(hexes), json.dumps(flat, separators=(",", ":"))))
    print("drones:", len(pts))


if __name__ == "__main__":
    main()
